
-- Week 2: HNSW vector search lab.
CREATE EXTENSION IF NOT EXISTS vector;

-- Lab table.
CREATE TABLE IF NOT EXISTS faq_hnsw_lab (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_key TEXT NOT NULL UNIQUE,
    course TEXT NOT NULL,
    section TEXT NOT NULL,
    question TEXT NOT NULL,
    answer TEXT NOT NULL,
    embedding VECTOR(384) NOT NULL,
    embedding_model TEXT NOT NULL
);

-- Full HNSW index.
CREATE INDEX IF NOT EXISTS ix_faq_hnsw_lab_embedding_hnsw
ON faq_hnsw_lab
USING hnsw (embedding vector_cosine_ops)
WITH (
    m = 16,
    ef_construction = 64
);

-- Partial HNSW index.
CREATE INDEX IF NOT EXISTS ix_faq_hnsw_lab_llm_partial
ON faq_hnsw_lab
USING hnsw (embedding vector_cosine_ops)
WITH (
    m = 16,
    ef_construction = 64
)
WHERE course = 'llm-zoomcamp'
  AND embedding_model = 'sentence-transformers/all-MiniLM-L6-v2';
